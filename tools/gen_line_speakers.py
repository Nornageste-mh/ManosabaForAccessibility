#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 LineSpeakers.cs —— 「这一行是谁说的」的静态表（逐作层说话人兜底依据）。

为什么需要它
------------
本作运行时拿不到可靠的说话人：
  · `PrintedMessage.author` 的 `id`/`label` 实测为空串（run probe-speaker：
    `HOOK print author id=[] label=[]`）；
  · 名字框钩子 `RevealableTextPrinterPanel.SetAuthorNameText` 同样拿到空串
    （`HOOK advAuthorName=[]`）—— 本作的名字牌由 `WitchTrials.Views.AuthorTextBuilder`
    用角色数据资源自己拼，不走基类那条显示文本。
所以「谁在说话」只能从剧本本身的注释行取：中文本地化文档里每句台词前都有
    ; > Ema: |#0101Adv02_Ema001|
作者 id 就写在这条注释里，行 id 与运行时 `PrintedMessage.Text.parts[0].id` 完全一致
（probe4 实查），因此可以在运行时用行 id 查这张表。

数据来源
--------
`textassets/scripts/zh-Hans/**/*.txt`（text-extract 从 Addressables 的
`general-localization-zhhans-scripts-*` 提取，440 个文本、34k 行）。
只取 `; > <AuthorId>: |#<lineId>|` 这一种注释，gzip 后 base64 嵌进 C# 常量。
**不含任何剧情文本**，只有「行 id → 作者 id」的对应关系，符合仓库 IP 红线。

用法
----
    python tools/gen_line_speakers.py            # 重新生成 mod/src/ManosabaA11y/LineSpeakers.cs
    python tools/gen_line_speakers.py --check    # 只校验现有文件是否与数据源一致
"""

import argparse
import base64
import gzip
import hashlib
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPTS = os.path.join(ROOT, "textassets", "scripts", "zh-Hans")
OUT = os.path.join(ROOT, "mod", "src", "ManosabaA11y", "LineSpeakers.cs")

# ; > Ema: |#0101Adv02_Ema001|
LINE_RE = re.compile(r"^;\s*>\s*([A-Za-z][A-Za-z0-9_]*)\s*:[^|]*\|\#([^|]+)\|")

TEMPLATE = """// <auto-generated>
// 本文件由 tools/gen_line_speakers.py 生成，不要手改。
// 数据来源：textassets/scripts/zh-Hans（{files} 个文本 → {count} 条「行 id → 作者 id」）
// 内容：只有行 id 与作者 id 的对应关系，不含任何剧情文本。
// </auto-generated>
using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Text;

namespace ManosabaA11y
{{
    /// <summary>
    /// 「这一行是谁说的」的静态表（说话人兜底依据）。
    ///
    /// 判定链：<c>PrintedMessage.Text.parts[0].id</c>（例 <c>0101Adv02_Ema001</c>）
    /// → 查本表得到作者 id（例 <c>Ema</c>）→ <see cref="SpeakerNames.Resolve"/> 转中文名。
    ///
    /// 为什么必须静态表：本作运行时 `PrintedMessage.author` 的 id/label 为空串，
    /// 名字框钩子也拿到空串（见 tools/gen_line_speakers.py 顶部说明）。
    ///
    /// 体积：{count} 条，gzip+base64 后约 {kb} KB 源码常量，启动时解压一次进字典。
    /// </summary>
    internal static class LineSpeakers
    {{
        private const string Gz = {payload};

        private static Dictionary<string, string> _map;

        private static Dictionary<string, string> Map
        {{
            get
            {{
                if (_map != null) return _map;
                var map = new Dictionary<string, string>(StringComparer.Ordinal);
                try
                {{
                    byte[] raw = Convert.FromBase64String(Gz);
                    using (var ms = new MemoryStream(raw))
                    using (var gz = new GZipStream(ms, CompressionMode.Decompress))
                    using (var sr = new StreamReader(gz, Encoding.UTF8))
                    {{
                        string line;
                        while ((line = sr.ReadLine()) != null)
                        {{
                            int tab = line.IndexOf('\\t');
                            if (tab <= 0 || tab + 1 >= line.Length) continue;
                            map[line.Substring(0, tab)] = line.Substring(tab + 1);
                        }}
                    }}
                }}
                catch (Exception e)
                {{
                    // 解压失败只影响「说话人名字」，正文朗读不受影响 → 降级为无说话人。
                    A11yHost.Diag("LineSpeakers: 解压失败 " + e.Message);
                }}
                _map = map;
                return _map;
            }}
        }}

        /// <summary>表里有多少条（诊断用）。</summary>
        internal static int Count {{ get {{ return Map.Count; }} }}

        /// <summary>行 id → 作者 id；表未命中返回空串。</summary>
        internal static string AuthorOf(string lineId)
        {{
            if (string.IsNullOrEmpty(lineId)) return "";
            try
            {{
                string id;
                return Map.TryGetValue(lineId, out id) ? id : "";
            }}
            catch {{ return ""; }}
        }}
    }}
}}
"""


def scan():
    if not os.path.isdir(SCRIPTS):
        sys.exit("找不到数据源：%s（先跑 tools/extract_scripts.py）" % SCRIPTS)
    mapping = {}
    files = 0
    for dirpath, _dirnames, filenames in os.walk(SCRIPTS):
        for name in filenames:
            if not name.lower().endswith(".txt"):
                continue
            files += 1
            path = os.path.join(dirpath, name)
            with io.open(path, "r", encoding="utf-8-sig", errors="replace") as f:
                for line in f:
                    m = LINE_RE.match(line)
                    if not m:
                        continue
                    author, line_id = m.group(1), m.group(2).strip()
                    # 同一行 id 若出现多次（本地化文档重复），以第一条为准
                    if line_id and line_id not in mapping:
                        mapping[line_id] = author
    return mapping, files


def build_source():
    mapping, files = scan()
    ids = sorted(mapping)
    payload = "\n".join("%s\t%s" % (k, mapping[k]) for k in ids)
    raw = payload.encode("utf-8") if sys.version_info < (3,) else payload.encode("utf-8")
    buf = io.BytesIO()
    # mtime=0：同一份数据源生成同一份源码（可复现构建）
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as gz:
        gz.write(raw)
    packed = buf.getvalue()
    b64 = base64.b64encode(packed).decode("ascii")
    chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    literal = (" +\n            ").join('"%s"' % c for c in chunks)
    literal = "\n            " + literal
    return TEMPLATE.format(files=files, count=len(ids), kb=len(packed) // 1024,
                           payload=literal), ids, packed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = ap.parse_args()

    src, ids, packed = build_source()
    digest = hashlib.sha256("\n".join(ids).encode("utf-8")).hexdigest()[:16]

    if args.check:
        if not os.path.exists(OUT):
            sys.exit("缺少输出文件：%s" % OUT)
        old = io.open(OUT, "r", encoding="utf-8").read()
        ok = old == src
        print("check: %s  rows=%d digest=%s" % ("OK" if ok else "STALE", len(ids), digest))
        sys.exit(0 if ok else 1)

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print("生成 %s" % OUT)
    print("  rows=%d  gzip=%d B  digest=%s" % (len(ids), len(packed), digest))


if __name__ == "__main__":
    main()
