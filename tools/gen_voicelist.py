#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 VoiceLineIds.cs —— 「这一行有没有游戏配音」的静态表（逐作层唯一判定依据）。

为什么需要它
------------
本作对白配音覆盖率 98.2%、审判辩论 99.4%，而旁白几乎没有配音（0.1%）。
有配音的行如果读屏再念一遍中文文本，两边会叠在一起、互相盖住；
所以逐作层的标准做法是：**有配音的行不自动朗读**（语音已经在念），
但仍然记进重读缓冲区 —— 玩家按重读键时可以用 TTS 再听一遍中文。

怎么判定
--------
语音 clip 的文件名就是剧本行 id（`0101Trial01_Sherry001` 这种）。
运行时从 `PrintedMessage.Text.parts[i].id` 拿到当前行的 id（probe4 实查），
再查这张静态表即可 —— 与当前 locale 无关，切中/日文都不影响判定。

数据来源
--------
`textassets/voice-index.tsv`（text-extract 用 UnityPy 从 `general-voice-*.bundle`
提取，26084 行，列：bundle / container / clip_name / path_id）。
只取 clip_name 列、去重、排序，gzip 后 base64 嵌进 C# 常量。
**不含任何音频数据**，只有文件名（= 行 id），符合仓库的 IP 红线。

用法
----
    python tools/gen_voicelist.py            # 重新生成 mod/src/ManosabaA11y/VoiceLineIds.cs
    python tools/gen_voicelist.py --check    # 只校验现有文件是否与数据源一致
"""

import argparse
import base64
import gzip
import hashlib
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TSV = os.path.join(ROOT, "textassets", "voice-index.tsv")
OUT = os.path.join(ROOT, "mod", "src", "ManosabaA11y", "VoiceLineIds.cs")

TEMPLATE = """// <auto-generated>
// 本文件由 tools/gen_voicelist.py 生成，不要手改。
// 数据来源：textassets/voice-index.tsv（{rows} 行 → {count} 个唯一行 id）
// 内容：只含语音 clip 的文件名（= 剧本行 id），不含任何音频数据。
// </auto-generated>
using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Text;

namespace ManosabaA11y
{{
    /// <summary>
    /// 「这一行有没有游戏配音」的静态表（逐作层唯一判定依据）。
    ///
    /// 判定链：<c>PrintedMessage.Text.parts[i].id</c>（probe4 实查，例：
    /// <c>0101Adv05_Narrative001</c>）→ 查 <see cref="Voiced"/>。
    /// 与当前文本语言无关（id 是行标识，不随 locale 变）。
    ///
    /// 为什么不做成运行时探测：<c>Naninovel.AudioManager</c> 没有「当前正在播哪个配音」
    /// 的公开入口（只暴露 Volume / PlayVoice / StopVoice），拿不到「这句有没有配音」。
    /// 所以只能靠静态表 —— 这也是《不存在》《钟塔》等仓库的同一做法。
    ///
    /// 体积：{count} 个 id，gzip+base64 后约 {kb} KB 源码常量，启动时解压一次进 HashSet。
    /// </summary>
    internal static class VoiceLineIds
    {{
        private const string Gz = {payload};

        private static HashSet<string> _voiced;

        /// <summary>有配音的行 id 集合（首次访问时解压）。</summary>
        internal static HashSet<string> Voiced
        {{
            get
            {{
                if (_voiced != null) return _voiced;
                var set = new HashSet<string>(StringComparer.Ordinal);
                try
                {{
                    byte[] raw = Convert.FromBase64String(Gz);
                    using (var ms = new MemoryStream(raw))
                    using (var gz = new GZipStream(ms, CompressionMode.Decompress))
                    using (var sr = new StreamReader(gz, Encoding.UTF8))
                    {{
                        string line;
                        while ((line = sr.ReadLine()) != null)
                        {{
                            if (line.Length > 0) set.Add(line);
                        }}
                    }}
                }}
                catch (Exception e)
                {{
                    // 解压失败不能让朗读链崩：退回「空表」= 每行都当无配音照常朗读，
                    // 行为退化为「全部朗读」，比整部游戏没声音好。
                    A11yHost.Diag("VoiceLineIds: 解压失败 " + e.Message);
                }}
                _voiced = set;
                return _voiced;
            }}
        }}

        /// <summary>表里有多少行 id（诊断用）。</summary>
        internal static int Count {{ get {{ return Voiced.Count; }} }}

        /// <summary>这一行的 id 有没有配音。id 为空/表未命中一律返回 false（= 照常朗读）。</summary>
        internal static bool Has(string lineId)
        {{
            if (string.IsNullOrEmpty(lineId)) return false;
            try {{ return Voiced.Contains(lineId); }}
            catch {{ return false; }}
        }}
    }}
}}
"""


def load_ids():
    if not os.path.exists(TSV):
        sys.exit("找不到数据源：%s（先跑 tools/extract_voice.py）" % TSV)
    ids = set()
    rows = 0
    with io.open(TSV, "r", encoding="utf-8") as f:
        header = f.readline()
        for line in f:
            line = line.rstrip("\r\n")
            if not line:
                continue
            rows += 1
            cols = line.split("\t")
            if len(cols) < 3:
                continue
            clip = cols[2].strip()
            if clip:
                ids.add(clip)
    return sorted(ids), rows


def build_source():
    ids, rows = load_ids()
    payload = "\n".join(ids).encode("utf-8")
    buf = io.BytesIO()
    # mtime=0：同一份数据源生成同一份源码（可复现构建）
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as gz:
        gz.write(payload)
    raw = buf.getvalue()
    b64 = base64.b64encode(raw).decode("ascii")

    # 拆成每行 100 字符的字符串字面量再用 + 拼接，避免单行过长（也便于 diff）
    chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    literal = (" +\n            ").join('"%s"' % c for c in chunks)
    literal = "\n            " + literal
    return TEMPLATE.format(rows=rows, count=len(ids), kb=len(raw) // 1024,
                           payload=literal), ids, raw


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = ap.parse_args()

    src, ids, raw = build_source()
    digest = hashlib.sha256("\n".join(ids).encode("utf-8")).hexdigest()[:16]

    if args.check:
        if not os.path.exists(OUT):
            sys.exit("缺少输出文件：%s" % OUT)
        old = io.open(OUT, "r", encoding="utf-8").read()
        ok = old == src
        print("check: %s  ids=%d digest=%s" % ("OK" if ok else "STALE", len(ids), digest))
        sys.exit(0 if ok else 1)

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print("生成 %s" % OUT)
    print("  ids=%d  源数据 %d 行  gzip=%d B  digest=%s" % (len(ids), 26084, len(raw), digest))


if __name__ == "__main__":
    main()
