import io, os, glob
root = "D:/DSHWorkSpace/manosaba_a11y/textassets/scripts/zh-Hans"
paths = []
for p in glob.glob(root + "/**/*.txt", recursive=True):
    rel = os.path.relpath(p, root).replace("\\", "/")[:-4]
    paths.append(rel)
paths.sort()
print("count:", len(paths))
print("sample:", paths[:3], "...", paths[-2:])
out = io.open("D:/DSHWorkSpace/manosaba_a11y/mod/src/ManosabaA11y/ScriptIndex.cs", "w", encoding="utf-8-sig", newline="\n")
out.write("// <auto-generated>\n")
out.write("// 由 tools/gen_script_index.py 生成，不要手改。\n")
out.write("// 内容是**剧本路径**（Naninovel 脚本名），不含任何台词原文。\n")
out.write("// </auto-generated>\n")
out.write("namespace ManosabaA11y\n{\n")
out.write("    /// <summary>\n")
out.write("    /// 全部剧本路径（440 个）。开发者跳转菜单的数据源。\n")
out.write("    /// 为什么不从游戏里动态枚举：剧本是 Addressables 资源，运行时只有一个\n")
out.write("    /// <see cref=\"Naninovel.Script\"/> 被加载；要列全部就得知道资源清单，\n")
out.write("    /// 而清单本身来自我们提取的 textassets 索引，是最稳的来源。\n")
out.write("    /// </summary>\n")
out.write("    internal static class ScriptIndex\n    {\n")
out.write("        internal static readonly string[] All =\n        {\n")
for s in paths:
    out.write('            "' + s + '",\n')
out.write("        };\n\n")
out.write("        internal static int Count => All.Length;\n\n")
out.write("        /// <summary>按前缀找第一个剧本（跳转菜单里「跳到某章开头」用）。</summary>\n")
out.write("        internal static int IndexOfPrefix(string prefix)\n        {\n")
out.write("            if (string.IsNullOrEmpty(prefix)) return -1;\n")
out.write("            for (int i = 0; i < All.Length; i++)\n")
out.write("                if (All[i].StartsWith(prefix, System.StringComparison.OrdinalIgnoreCase)) return i;\n")
out.write("            return -1;\n        }\n")
out.write("    }\n}\n")
out.close()
print("written ScriptIndex.cs")
